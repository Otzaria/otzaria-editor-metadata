"use strict";

const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { execFileSync } = require("node:child_process");

const root = path.resolve(__dirname, "..");
const htmlPath = path.join(root, "index.html");
const html = fs.readFileSync(htmlPath, "utf8");
const generatedStyle = /<style id="compiled-styles">[\s\S]*?<\/style>/g;
if ([...html.matchAll(generatedStyle)].length !== 1) {
  throw new Error("Expected exactly one compiled-styles block in index.html");
}

// Exclude generated CSS/font data from the next scan. The HTML and JavaScript
// remain the source of truth, including className and classList string literals.
const content = html.replace(generatedStyle, "");
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), "metadata-styles-"));
let utilities;
try {
  fs.writeFileSync(path.join(temporary, "content.html"), content);
  fs.writeFileSync(path.join(temporary, "input.css"),
    "@tailwind base;\n@tailwind components;\n@tailwind utilities;\n");
  execFileSync(process.execPath, [
    require.resolve("tailwindcss/lib/cli.js"),
    "--input", path.join(temporary, "input.css"),
    "--content", path.join(temporary, "content.html"),
    "--output", path.join(temporary, "output.css"),
    "--minify",
  ], { cwd: root, stdio: "pipe" });
  utilities = fs.readFileSync(path.join(temporary, "output.css"), "utf8").trim();
} finally {
  fs.rmSync(temporary, { recursive: true, force: true });
}

const fontRoot = path.dirname(require.resolve("@fontsource-variable/inter/package.json"));
// Keep the original Inter family, normal style, variable weights and all seven
// language subsets. Hebrew continues to use the same sans-serif fallback.
const fonts = fs.readFileSync(path.join(fontRoot, "wght.css"), "utf8")
  .replaceAll("'Inter Variable'", "'Inter'")
  .replace(/url\(\.\/files\/([^)]*)\)/g, (_match, filename) => {
    const data = fs.readFileSync(path.join(fontRoot, "files", filename));
    return `url(data:font/woff2;base64,${data.toString("base64")})`;
  });
const licenses = [
  "Generated by npm run build:styles. Do not edit this block manually.",
  "Tailwind CSS 3.4.17",
  fs.readFileSync(require.resolve("tailwindcss/LICENSE"), "utf8").trim(),
  "Inter variable font, @fontsource-variable/inter 5.2.8",
  fs.readFileSync(path.join(fontRoot, "LICENSE"), "utf8").trim(),
].join("\n\n");
const block = `<style id="compiled-styles">\n/*\n${licenses}\n*/\n${fonts}\n${utilities}\n</style>`;
const output = html.replace(generatedStyle, () => block);

if (process.argv.includes("--check")) {
  if (output !== html) {
    console.error("Styles are out of date. Run npm run build:styles and commit index.html.");
    process.exitCode = 1;
  } else {
    console.log("Embedded styles and fonts match the pinned build.");
  }
} else {
  fs.writeFileSync(htmlPath, output);
  console.log(`Embedded ${Buffer.byteLength(utilities)} bytes of Tailwind CSS and local Inter fonts.`);
}
